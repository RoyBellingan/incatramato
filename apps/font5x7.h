inline const unsigned char* glyph(char c) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    return (c >= 32 && c <= 90) ? kGlyphs[c - 32] : kGlyphs[0];
}

